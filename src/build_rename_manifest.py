#!/usr/bin/env python3
"""
Generate the Drive rename manifest and a runnable Apps Script.

The Drive integration available to this project is read-only for titles, so
renaming happens on the client's side. This produces two artifacts:

  data/rename_manifest.csv  — file_id, current_title, proposed_title, outcome
  docs/rename.gs            — Apps Script with the pairs embedded, ready to paste

The script is deliberately idempotent and reversible: it skips files already
carrying a suffix, and the CSV retains every original title so the operation
can be undone.
"""
import csv
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CALLS = ROOT / "data" / "calls"
CSV_OUT = ROOT / "data" / "rename_manifest.csv"
GS_OUT = ROOT / "docs" / "rename.gs"

SUFFIX = {
    "closed": "Closed",
    "follow_up": "Follow Up",
    "lost": "Lost",
    "undetermined": "Undetermined",
}
SEP = " — "          # em dash, matches the display_title convention


def _title_name(t):
    """Best guess at the prospect name a title claims, for mismatch detection."""
    t = re.sub(r"^\d{2}/\d{2}/\d{4}\s*-\s*", "", t or "")
    t = re.split(r"\s+[x&]\s+|\s+and\s+", t, flags=re.I)[0]
    t = re.sub(r"[^A-Za-zÀ-ÿ\s'-]", "", t).strip().lower()
    return "" if ("impromptu" in t or "zoom" in t) else t


def build():
    rows = []
    for f in sorted(CALLS.glob("*.json")):
        rec = json.loads(f.read_text())
        src, out = rec.get("source", {}), rec.get("outcome", {})
        fid, title = src.get("drive_file_id"), src.get("original_title")
        disp = out.get("disposition")
        if not (fid and title and disp):
            continue
        label = SUFFIX.get(disp, disp)
        if SEP in title and title.rstrip().endswith(label):
            continue                                   # already applied

        # Untitled recordings say only "Impromptu Zoom Meeting". Appending an
        # outcome alone leaves them nearly as unusable as before, so inject the
        # prospect name we recovered from the transcript — parenthetically, so
        # the original title survives intact and the addition is obvious.
        #
        # Separately: ~5% of titles name the WRONG person. Renaming those to
        # "<wrong name> — Closed" would launder a data error into something
        # that looks authoritative, so they get the corrected name too and are
        # reported for review rather than silently fixed.
        stem = title.rstrip()
        prospect = rec.get("prospect", {}).get("name")
        named = rec.get("call", {}).get("prospect_named_in_title", True)
        mismatch = False
        if prospect:
            tn = _title_name(title)
            pn = prospect.lower()
            if not named:
                if prospect.lower() not in stem.lower():
                    stem = f"{stem} ({prospect})"
            elif tn:
                tf = tn.split()[0] if tn.split() else ""
                pf = pn.split()[0] if pn.split() else ""
                if tf and pf and tf != pf and tf not in pn and pf not in tn:
                    mismatch = True
                    stem = f"{stem} [actually: {prospect}]"

        rows.append({
            "file_id": fid,
            "current_title": title,
            "proposed_title": f"{stem}{SEP}{label}",
            "outcome": disp,
            "confidence": out.get("confidence"),
            "rep": rec.get("rep", {}).get("name"),
            "call_date": rec.get("call", {}).get("date"),
            "name_mismatch": mismatch,
        })
    return rows


APPS_SCRIPT = """/**
 * Primal Instinct — append call outcome to transcript filenames.
 *
 * Generated by src/build_rename_manifest.py. %(n)d files.
 *
 * HOW TO RUN
 *   1. script.google.com  →  New project
 *   2. Paste this whole file, replacing the default contents
 *   3. Run `dryRun` first. It logs every change WITHOUT touching anything.
 *   4. Read the log. If it looks right, run `applyRenames`.
 *   5. To undo, run `revertRenames`.
 *
 * You must be signed in as an account with edit rights on the transcripts
 * folder. The files are owned by info@primalinstinct.net — if you only have
 * view access, ask them to run it instead.
 *
 * Safe to re-run: files already carrying the suffix are skipped.
 */

var RENAMES = %(pairs)s;

function dryRun()        { _process(false); }
function applyRenames()  { _process(true);  }

function _process(commit) {
  var ok = 0, skipped = 0, failed = 0;
  Logger.log(commit ? '=== APPLYING RENAMES ===' : '=== DRY RUN — no changes ===');
  for (var i = 0; i < RENAMES.length; i++) {
    var r = RENAMES[i];
    try {
      var file = DriveApp.getFileById(r.id);
      var now = file.getName();
      if (now === r.to) { skipped++; continue; }
      if (now !== r.from) {
        Logger.log('SKIP (title changed since manifest): ' + now);
        skipped++;
        continue;
      }
      if (commit) file.setName(r.to);
      Logger.log((commit ? 'RENAMED: ' : 'WOULD RENAME: ') + now + '  ->  ' + r.to);
      ok++;
    } catch (e) {
      Logger.log('FAILED ' + r.id + ': ' + e.message);
      failed++;
    }
  }
  Logger.log('--- ' + ok + ' processed, ' + skipped + ' skipped, ' + failed + ' failed ---');
}

function revertRenames() {
  var ok = 0, failed = 0;
  for (var i = 0; i < RENAMES.length; i++) {
    var r = RENAMES[i];
    try {
      var file = DriveApp.getFileById(r.id);
      if (file.getName() === r.to) { file.setName(r.from); ok++; }
    } catch (e) {
      Logger.log('REVERT FAILED ' + r.id + ': ' + e.message);
      failed++;
    }
  }
  Logger.log('--- reverted ' + ok + ', failed ' + failed + ' ---');
}
"""


def main():
    rows = build()
    CSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    GS_OUT.parent.mkdir(parents=True, exist_ok=True)

    with CSV_OUT.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["file_id", "current_title", "proposed_title",
                                           "outcome", "confidence", "rep", "call_date",
                                           "name_mismatch"])
        w.writeheader()
        w.writerows(rows)

    pairs = json.dumps([{"id": r["file_id"], "from": r["current_title"],
                         "to": r["proposed_title"]} for r in rows], indent=2)
    GS_OUT.write_text(APPS_SCRIPT % {"n": len(rows), "pairs": pairs})

    by_outcome = {}
    for r in rows:
        by_outcome[r["outcome"]] = by_outcome.get(r["outcome"], 0) + 1
    print(f"{len(rows)} renames staged")
    for k, v in sorted(by_outcome.items(), key=lambda x: -x[1]):
        print(f"  {k:14} {v}")
    print(f"\nWrote {CSV_OUT.relative_to(ROOT)}")
    print(f"Wrote {GS_OUT.relative_to(ROOT)}")
    low = [r for r in rows if (r["confidence"] or 1) < 0.7]
    if low:
        print(f"\n{len(low)} rename(s) rest on a low-confidence outcome (<0.70) — review these first:")
        for r in low[:10]:
            print(f"  {r['confidence']}  {r['proposed_title'][:78]}")

    bad = [r for r in rows if r["name_mismatch"]]
    if bad:
        print(f"\n{len(bad)} title(s) name the WRONG PERSON — corrected name appended in brackets.")
        print("Review these before running the script; the underlying Drive titles are wrong at source:")
        for r in bad[:10]:
            print(f"  {r['proposed_title'][:100]}")


if __name__ == "__main__":
    main()
